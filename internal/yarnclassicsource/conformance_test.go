func newYarnFixture(t *testing.T) yarnFixture {
	t.Helper()
	root := filepath.Join(t.TempDir(), "project")
	work := filepath.Join(t.TempDir(), "capture-work")
	if err := os.MkdirAll(filepath.Join(root, "packages", "workspace"), 0o700); err != nil {
		t.Fatal(err)
	}
	rootManifest := map[string]any{"name": "app", "version": "1.0.0", "private": true, "workspaces": map[string]any{"packages": []string{"packages/*"}, "nohoist": []string{"workspace/b"}}, "dependencies": map[string]string{"a": "^1.0.0", "workspace": "1.0.0"}, "optionalDependencies": map[string]string{"opt": "^1.0.0"}}
	workspaceManifest := map[string]any{"name": "workspace", "version": "1.0.0", "dependencies": map[string]string{"b": "^1.0.0"}}
	packages := []fixturePackage{
		{name: "a", version: "1.0.0", metadata: map[string]any{"dependencies": map[string]string{"b": "^1.0.0"}}, files: map[string][]byte{"index.js": []byte("module.exports=require('b')\n")}},
		{name: "b", version: "1.0.0", metadata: map[string]any{}, files: map[string][]byte{"index.js": []byte("module.exports='b'\n")}},
		{name: "opt", version: "1.0.0", metadata: map[string]any{"os": []string{"linux"}}, files: map[string][]byte{"index.js": []byte("module.exports='opt'\n")}},
	}
	entries := []string{}
	payloadByName := map[string][]byte{}
	pathByName := map[string]string{}
	for _, pkg := range packages {
		payload := buildTGZ(t, pkg)
		sum := sha512.Sum512(payload)
		integrity := "sha512-" + base64.StdEncoding.EncodeToString(sum[:])
		resolved := fmt.Sprintf("https://registry.yarnpkg.com/%s/-/%s-%s.tgz#pinned", pkg.name, pkg.name, pkg.version)
		entry := fmt.Sprintf("%s@^1.0.0:\n  version \"%s\"\n  resolved \"%s\"\n  integrity %s\n", pkg.name, pkg.version, resolved, integrity)
		if dependencies, ok := pkg.metadata["dependencies"].(map[string]string); ok {
			entry += "  dependencies:\n"
			for _, name := range sortedMapKeys(dependencies) {
				entry += fmt.Sprintf("    %s \"%s\"\n", name, dependencies[name])
			}
		}
		entries = append(entries, entry)
		payloadByName[pkg.name] = payload
		file := filepath.Join(t.TempDir(), pkg.name+"-1.0.0.tgz")
		if err := os.WriteFile(file, payload, 0o600); err != nil {
			t.Fatal(err)
		}
		pathByName[pkg.name] = file
	}
	lockBytes := []byte("# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n" + strings.Join(entries, "\n"))
	rootBytes := mustJSON(t, rootManifest)
	workspaceBytes := mustJSON(t, workspaceManifest)
	writeFile(t, filepath.Join(root, "package.json"), rootBytes)
	writeFile(t, filepath.Join(root, "yarn.lock"), lockBytes)
	writeFile(t, filepath.Join(root, "index.js"), []byte("require('a')\n"))
	writeFile(t, filepath.Join(root, "packages", "workspace", "package.json"), workspaceBytes)
	writeFile(t, filepath.Join(root, "packages", "workspace", "index.js"), []byte("require('b')\n"))
	request := ParseRequest{LockName: "yarn.lock", LockBytes: lockBytes, Manifests: map[string][]byte{"package.json": rootBytes, "packages/workspace/package.json": workspaceBytes}, YarnVersion: SupportedYarnVersion, AllowedRegistryOrigins: []string{"https://registry.yarnpkg.com/"}, Target: Target{OS: "darwin", Architecture: "arm64", Libc: "none", IncludeDev: true}}
	graph, err := Parse(request)
	if err != nil {
		t.Fatal(err)
	}
	tarballs := map[string]RawTarball{}
	payloads := map[string][]byte{}
	for _, pkg := range graph.Packages {
		if pkg.Resolved != "" {
			tarballs[pkg.Key] = RawTarball{Path: pathByName[pkg.Name]}
			payloads[pkg.Key] = payloadByName[pkg.Name]
		}
	}
	return yarnFixture{root: root, work: work, request: request, tarballs: tarballs, payloads: payloads, graph: graph}
}

