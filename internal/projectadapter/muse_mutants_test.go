package projectadapter

import (
	"encoding/json"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// Claim: each bounded source plant hits the intended regression assertion.
// Setup errors, build failures and absent plants never count as detection.
// The controls cover offline preflight/verification and typed launch refusal;
// they do not establish native runtime qualification.
func TestMuseNarrowingMutants(t *testing.T) {
	if os.Getenv("CURATOR_MUSE_ADAPTER_MUTANTS") != "1" {
		t.Skip("explicit bounded mutation lane")
	}
	_ = offlineHome(t) // Preserve the supported filesystem/platform bound.
	cases := []struct{ name, file, pkg, test, old, new, witness string }{
		{"project-document-first", "../projectcontext/composition_types.go", "../projectcontext", "TestMuseOfflineComposition", `return bytes.Join(parts, []byte{'\n'})`, `if len(parts)>1 { parts[0],parts[len(parts)-1]=parts[len(parts)-1],parts[0] }; return bytes.Join(parts, []byte{'\n'})`, "profile-first exact separator lost"},
		{"repository-approval-imported", "muse.go", ".", "TestMuseRepositoryControls/config/muse/approval.json", `func musePath(p string) bool {`, `func musePath(p string) bool { if p == "config/muse/approval.json" { return true }`, "want unapproved_control_path"},
		{"interactive-allowed", "muse.go", ".", "TestMuseLaunchRefused", `return LaunchContribution{}, &Unsupported{LaunchForm, "interactive_and_resume_unqualified"}`, `return LaunchContribution{}, nil`, "unsafe launch accepted"},
		{"native-project-allowed", "muse.go", ".", "TestMuseLaunchRefused", `return LaunchContribution{}, &Unsupported{Permissions, "manager_permissions_unqualified; project sources not isolated"}`, `return LaunchContribution{}, nil`, "unsafe launch accepted"},
		{"native-project-notice", "muse.go", ".", "TestMuseLaunchRefused", `report.Notice = "project sources not isolated"`, `report.Notice = ""`, "native source warning missing"},
		{"file-count", "muse.go", ".", "TestMuseOfflineBounds/count", `len(input.Files) > 10000`, `false`, "want complete receipt required"},
		{"file-byte-cap", "muse.go", ".", "TestMuseOfflineBounds/file", `len(b) > 16<<20`, `false`, "want generated bytes or metadata differ"},
		{"total-byte-cap", "muse.go", ".", "TestMuseOfflineBounds/total", `if total > 64<<20 {`, `if total > 64<<20 && false {`, "want generated byte bound exceeded"},
		{"policy-json", "muse.go", ".", "TestMuseOfflineBounds/policy-json", `!json.Valid(input.PolicyRecord)`, `false && !json.Valid(input.PolicyRecord)`, "want manager policy or memory differs"},
		{"existing-home", "muse.go", ".", "TestMuseOfflinePreservesExisting", `parent.Mkdir(name, 0700)`, `parent.MkdirAll(name, 0700)`, "want already exists"},
		{"cancellation", "muse.go", ".", "TestMuseOfflinePreservesExisting", `func MaterializeMuseOffline(ctx context.Context, home string, input MuseOfflineInput) (MuseOfflineHome, error) {`, `func MaterializeMuseOffline(ctx context.Context, home string, input MuseOfflineInput) (MuseOfflineHome, error) { ctx=context.Background()`, "cancelled preparation"},
		{"memory-on", "muse.go", ".", "TestMuseOfflineInputGates/memory", `input.Memory != "off" || `, ``, "want manager policy or memory differs"},
		{"policy-hash", "muse.go", ".", "TestMuseOfflineInputGates/policy", `sum(input.PolicyRecord) != input.PolicySHA256`, `false`, "want manager policy or memory differs"},
		{"receipt-incomplete", "muse.go", ".", "TestMuseOfflineInputGates/missing", `len(input.Files) != len(input.Generated)`, `false`, "want complete receipt required"},
		{"receipt-metadata", "muse.go", ".", "TestMuseOfflineInputGates/hash", `if !ok || s.SHA256 != sum(b) || s.Size != int64(len(b)) || (s.Mode != 0600 && s.Mode != 0700) || len(b) > 16<<20 {`, `if false && (!ok || s.SHA256 != sum(b) || s.Size != int64(len(b)) || (s.Mode != 0600 && s.Mode != 0700) || len(b) > 16<<20) {`, "want generated bytes or metadata differ"},
		{"path-alias", "muse.go", ".", "TestMuseOfflineInputGates/alias", `if aliases[alias] {`, `if aliases[alias] && false {`, "want generated path alias"},
		{"file-ancestor", "muse.go", ".", "TestMuseOfflineInputGates/ancestor", `if aliases[cases.Fold().String(norm.NFC.String(parent))] {`, `if aliases[cases.Fold().String(norm.NFC.String(parent))] && false {`, "want generated file ancestor collision"},
		{"required-mcp-omitted", "muse.go", ".", "TestMuseMCPDisposition", `if item.Required {`, `if item.Required && false {`, "required MCP was not refused"},
		{"mcp-identity", "muse.go", ".", "TestMuseIndependentMetadata", `if !identifiers.Valid(item.ItemID) || seen[item.ItemID] {`, `if false && (!identifiers.Valid(item.ItemID) || seen[item.ItemID]) {`, "want invalid MCP item identity"},
		{"drift-bytes", "muse.go", ".", "TestMuseOfflineDrift/bytes", `sum(b) != s.SHA256`, `sum(b) != s.SHA256 && false`, "want project_context_drift"},
		{"drift-size", "muse.go", ".", "TestMuseIndependentMetadata", `info.Size() != s.Size`, `false`, "want offline metadata differs"},
		{"drift-mode", "muse.go", ".", "TestMuseOfflineDrift/mode", `uint32(info.Mode().Perm()) != s.Mode`, `false`, "want project_context_drift"},
		{"missing-output", "muse.go", ".", "TestMuseOfflineDrift/missing", `if seen != len(generated) {`, `if seen != len(generated) && false {`, "want project_context_drift"},
		{"private-parent", "muse.go", ".", "TestMuseAllocationBoundaries", `if err = privatedir.Validate(parentPath); err != nil {`, `if err = privatedir.Validate(parentPath); err != nil && false {`, "want offline parent unavailable"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			source, err := os.ReadFile(tc.file)
			if err != nil {
				t.Fatal(err)
			}
			if strings.Count(string(source), tc.old) != 1 {
				t.Fatal("plant anchor count differs")
			}
			dir := t.TempDir()
			replacement := filepath.Join(dir, "mutant.go")
			if err = os.WriteFile(replacement, []byte(strings.Replace(string(source), tc.old, tc.new, 1)), 0600); err != nil {
				t.Fatal(err)
			}
			original, err := filepath.Abs(tc.file)
			if err != nil {
				t.Fatal(err)
			}
			b, _ := json.Marshal(map[string]any{"Replace": map[string]string{original: replacement}})
			overlay := filepath.Join(dir, "overlay.json")
			if err = os.WriteFile(overlay, b, 0600); err != nil {
				t.Fatal(err)
			}
			binary := os.Getenv("CURATOR_GO")
			if binary == "" {
				binary = "go"
			}
			cmd := exec.Command(binary, "test", "-count=1", "-overlay", overlay, "-run", "^"+tc.test+"$", tc.pkg)
			for _, value := range os.Environ() {
				if !strings.HasPrefix(value, "GIT_DIR=") && !strings.HasPrefix(value, "GIT_WORK_TREE=") {
					cmd.Env = append(cmd.Env, value)
				}
			}
			out, err := cmd.CombinedOutput()
			if err == nil || !strings.Contains(string(out), "--- FAIL:") || !strings.Contains(string(out), tc.witness) || strings.Contains(string(out), "[build failed]") {
				t.Fatalf("mutant missed intended assertion: %v\n%s", err, out)
			}
			t.Log("caught intended assertion:", tc.name)
		})
	}
}
